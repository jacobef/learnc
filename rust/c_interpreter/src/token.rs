use crate::source::Span;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Keyword {
    Auto,
    Bool,
    Break,
    Case,
    Char,
    Const,
    Complex,
    Continue,
    Default,
    Double,
    Do,
    Else,
    Enum,
    Extern,
    Float,
    For,
    Generic,
    Goto,
    If,
    Inline,
    Int,
    Long,
    Register,
    Restrict,
    Return,
    Short,
    Signed,
    Sizeof,
    Static,
    Struct,
    Switch,
    Typedef,
    Union,
    Unsigned,
    Void,
    Volatile,
    While,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenKind {
    Identifier(String),
    Number(String),
    CharLiteral(i64),
    WideCharLiteral(i64),
    StringLiteral(String),
    WideStringLiteral(String),
    Keyword(Keyword),
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Dot,
    Ellipsis,
    Semicolon,
    Star,
    StarEqual,
    Amp,
    DoubleAmp,
    AmpEqual,
    Caret,
    CaretEqual,
    Colon,
    Equal,
    DoubleEqual,
    Bang,
    BangEqual,
    Plus,
    PlusEqual,
    DoublePlus,
    Minus,
    MinusEqual,
    DoubleMinus,
    Arrow,
    Pipe,
    PipeEqual,
    DoublePipe,
    Slash,
    SlashEqual,
    Percent,
    PercentEqual,
    Question,
    Less,
    LessEqual,
    LeftShift,
    LeftShiftEqual,
    Greater,
    GreaterEqual,
    RightShift,
    RightShiftEqual,
    Tilde,
    Eof,
}

#[derive(Debug, Clone)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}
